"""Export the extracted acts from data/decisions.db as JSON, next to the schemas
that shaped them.

This writes `dataset/`, which is **committed**, unlike the database it reads.
That is deliberate: the working database is a 3.7 MB binary that changes every
night and cannot be diffed or reviewed, while the same content as JSON is
readable, greppable, and reviewable in a pull request. It is also the only
off-host copy of work that cost real money to produce — if this machine is lost,
`dataset/` is what survives.

Re-runnable; overwrites `dataset/` in place. Runs nightly from run_daily.sh.
"""

import json
import shutil
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "decisions.db"
OUT = ROOT / "dataset"

# table -> (json file, schema file in code/, Ukrainian act type)
TABLES = {
    "decisions": ("decisions.json", "extraction_schema.json", "Рішення Дисциплінарної палати"),
    "rulings": ("rulings.json", "ruling_schema.json", "Ухвала про відкриття дисциплінарної справи"),
    "reviews": ("reviews.json", "review_schema.json", "Рішення ВРП за скаргою на рішення ДП"),
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "schemas").mkdir(exist_ok=True)

    conn = sqlite3.connect(DB)
    manifest = {
        "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source_db": str(DB),
        "tables": {},
    }

    for table, (json_name, schema_name, act_type) in TABLES.items():
        rows = conn.execute(
            f"SELECT filename, data, processed_at, error FROM {table} ORDER BY filename"
        ).fetchall()

        records, errors = [], []
        for filename, data, processed_at, error in rows:
            if error or not data:
                errors.append({"filename": filename, "error": error})
                continue
            records.append(
                {
                    "filename": filename,
                    "processed_at": processed_at,
                    "data": json.loads(data),
                }
            )

        (OUT / json_name).write_text(
            json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        shutil.copy(ROOT / "code" / schema_name, OUT / "schemas" / schema_name)

        manifest["tables"][table] = {
            "act_type": act_type,
            "json": json_name,
            "schema": f"schemas/{schema_name}",
            "records": len(records),
            "errors": len(errors),
            "error_rows": errors,
        }
        print(f"{table:10s} {len(records):4d} records -> {json_name}  (schema: {schema_name})")

    (OUT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    # Generated rather than hand-written so the counts in it can never drift from
    # the files beside it — a README stating 161 records next to a file holding
    # 166 is worse than no README.
    (OUT / "README.md").write_text(readme(manifest), encoding="utf-8")
    conn.close()


def readme(manifest: dict) -> str:
    t = manifest["tables"]
    total = sum(v["records"] for v in t.values())
    rows = "\n".join(
        f"| `{v['json']}` | {v['records']} | `{v['schema']}` | {v['act_type']} |"
        for v in t.values()
    )
    return f"""# VRP extracted acts — JSON dataset

Structured data extracted from High Council of Justice (ВРП) disciplinary acts,
with the JSON Schemas that constrained the model's output. Regenerated by
`code/33_export_dataset.py` from the working database, and refreshed by the
nightly cycle.

**Generated:** {manifest["exported_at"]}

## Files

| file | records | schema | act type |
|---|---|---|---|
{rows}
| `manifest.json` | — | — | counts, source database, export timestamp |

{total} acts in total.

## Record shape

Each file is an array of envelopes, not bare schema objects:

```json
{{
  "filename": "1248_22.06.2026",        // act number _ date of adoption; the primary key
  "processed_at": "2026-07-29 12:57:37",
  "data": {{ }}                          // conforms to the matching schema, see the caveat
}}
```

`filename` is the join key back to the source act and to the register spreadsheet.

## Caveat: `data` is a superset of its schema

The schemas describe the **model's** output and set `additionalProperties: false`.
Two fields are added afterwards by rule, not by the model, so they appear in
`data` but not in the schema, and naive validation fails on every record:

- `complaint_number_candidates` — every disciplinary complaint number found in the
  act text by regex. All three act types.
- `reviewed_decision_candidates` — `reviews.json` only; the ДП decision numbers the
  review refers to.

The complaint number is the join key between an ухвала and the рішення that closes
it, so it is extracted deterministically rather than typed by the model.
`data.complaint_number` is the chosen value; the `_candidates` array is what the
regex saw. Strip those two keys and the records validate.

## Coverage

This is a **complete sweep back to a cut-off date, not a sample**: acts were
extracted newest-first, so nothing inside the covered window was skipped. Roughly
half the corpus — everything before November 2025 — has not been extracted yet.

Because an ухвала and the рішення that closes the case are 6–18 months apart, a
window reaching back only to late 2025 holds relatively few complete pairs.

The data is machine-extracted and has **not** been verified against the source
acts record by record.
"""


if __name__ == "__main__":
    main()
